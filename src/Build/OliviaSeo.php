<?php namespace ProcessWire;

/**
 * OliviaSeo — search-engine plumbing for generated sites.
 *
 * Writes a sitemap.xml and a robots.txt to the site web root so a freshly built
 * site is properly crawlable (SEO is the priority). Both carry an "Olivia"
 * marker: robots.txt is only written/removed when it's missing or Olivia-owned
 * (never clobbering a hand-written one), and rollback only deletes marked files.
 *
 * Per-page structured data (JSON-LD) and canonical URLs live in the views; this
 * class handles the two site-level files that need to sit at the web root.
 */
class OliviaSeo extends Wire {

	const ROBOTS_MARK  = '# Generated by Olivia';
	const SITEMAP_MARK = '<!-- Generated by Olivia -->';
	protected const TMP_TTL = 3600;
	protected static $tempsCleaned = false;

	public function wired() {
		if(!self::$tempsCleaned) {
			$this->cleanupStaleTemps();
			self::$tempsCleaned = true;
		}
		parent::wired();
	}

	/**
	 * Build is normally run from the CLI worker, where ProcessWire can't detect
	 * the request scheme and httpUrl() falls back to http://. Canonicals (rendered
	 * in the real web request) are https, so normalize these site-level files to
	 * https too to avoid mixed http/https signals — the modern/SEO default.
	 */
	protected function https(string $url): string {
		return preg_replace('#^http://#', 'https://', $url);
	}

	/** Write sitemap.xml + robots.txt; record what was written in the manifest. */
	public function writeForBuild(array &$manifest): void {
		// Ichiban ships its own XML sitemap generator + SEO — don't compete with it
		if($this->wire->modules->isInstalled('Ichiban')) return;
		$root = $this->wire->config->paths->root;
		$base = rtrim($this->https($this->wire->pages->get('/')->httpUrl), '/');

		try {
			$this->writeTextFile($root . 'sitemap.xml', $this->buildSitemap());
			$manifest['seo_files'][] = $root . 'sitemap.xml';
		} catch(\Throwable $e) {
			$manifest['errors'][] = 'seo sitemap: ' . $e->getMessage();
		}

		try {
			$robotsFile = $root . 'robots.txt';
			$raw = is_file($robotsFile) ? @file_get_contents($robotsFile) : '';
			$existing = is_string($raw) ? $raw : '';
			if($existing === '' || strpos($existing, self::ROBOTS_MARK) !== false) {
				$robots = self::ROBOTS_MARK . "\nUser-agent: *\nAllow: /\n\nSitemap: " . $base . "/sitemap.xml\n";
				$this->writeTextFile($robotsFile, $robots);
				$manifest['seo_files'][] = $robotsFile;
			} else {
				$manifest['errors'][] = 'seo robots: existing robots.txt kept (not Olivia-generated).';
			}
		} catch(\Throwable $e) {
			$manifest['errors'][] = 'seo robots: ' . $e->getMessage();
		}
	}

	/** Build a sitemap of public front-end pages (excludes admin/trash/404/unpublished). */
	protected function buildSitemap(): string {
		$adminRoot = $this->wire->config->adminRootPageID;
		$notFound  = $this->wire->config->http404PageID;
		$pages = $this->wire->pages->find("template!=admin, status<" . Page::statusUnpublished . ", include=hidden, limit=2000");

		$urls = '';
		foreach($pages as $p) {
			if($p->id === $notFound) continue;
			if($p->rootParent && $p->rootParent->id === $adminRoot) continue;
			$loc = $this->wire->sanitizer->entities($this->https($p->httpUrl));
			$mod = date('Y-m-d', $p->modified ?: time());
			$urls .= "  <url><loc>{$loc}</loc><lastmod>{$mod}</lastmod></url>\n";
		}

		return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
			. self::SITEMAP_MARK . "\n"
			. "<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n"
			. $urls
			. "</urlset>\n";
	}

	/** Remove Olivia-generated sitemap/robots during rollback. */
	public function removeForBuild(array $manifest, array &$report): void {
		$root = $this->wire->config->paths->root;
		foreach(($manifest['seo_files'] ?? []) as $file) {
			try {
				if(!is_file($file)) continue;
				$raw = @file_get_contents($file);
				if(!is_string($raw)) continue;
				$c = $raw;
				if(strpos($c, self::ROBOTS_MARK) === false && strpos($c, self::SITEMAP_MARK) === false) continue;
				if($this->wire->files->unlink($file, $root)) $report['files'][] = basename($file);
			} catch(\Throwable $e) {
				$report['errors'][] = 'seo remove ' . basename($file) . ': ' . $e->getMessage();
			}
		}
	}

	protected function writeTextFile(string $file, string $contents): void {
		$tmp = $file . '.' . getmypid() . '.' . str_replace('.', '', uniqid('', true)) . '.tmp';
		try {
			$this->wire->files->filePutContents($tmp, $contents);
			if(!@rename($tmp, $file)) throw new \RuntimeException('Could not replace Olivia SEO file');
		} finally {
			if(is_file($tmp)) @unlink($tmp);
		}
	}

	public function cleanupStaleTemps(): void {
		$root = $this->wire->config->paths->root;
		$files = array_merge(glob($root . 'sitemap.xml.*.tmp') ?: [], glob($root . 'robots.txt.*.tmp') ?: []);
		$cutoff = time() - self::TMP_TTL;
		foreach($files as $file) {
			$name = basename((string) $file);
			if(!$this->isTempName($name)) continue;
			$mtime = @filemtime($file);
			if($mtime !== false && $mtime < $cutoff) @unlink($file);
		}
	}

	protected function isTempName(string $name): bool {
		return (bool) preg_match('/^(?:sitemap\.xml|robots\.txt)\.\d+\.[a-f0-9]+\.tmp$/', $name);
	}
}
