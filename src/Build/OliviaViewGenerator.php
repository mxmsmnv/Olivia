<?php namespace ProcessWire;

/**
 * OliviaViewGenerator
 *
 * Writes self-contained Tailwind view files for templates Olivia created,
 * so generated pages actually render on the front end.
 *
 * Non-destructive:
 *  - only writes a file if it does not already exist
 *  - only targets templates created in this build (never profile templates
 *    like home / basic-page)
 *  - marks Olivia templates with noAppend/noPrependTemplateFile so the view
 *    renders standalone and the profile's _main.php is left alone
 *
 * Every file written is recorded in $manifest['files'] for rollback.
 */
class OliviaViewGenerator extends Wire {

	public const VIEW_VERSION = 34;
	public const HOME_VERSION = 17;
	public const MAX_BACKUP_FILE_BYTES = 512 * 1024;
	public const MAX_BACKUP_TOTAL_BYTES = 4 * 1024 * 1024;
	protected const TMP_TTL = 3600;
	protected static $tempsCleaned = false;

	public function wired() {
		if(!self::$tempsCleaned) {
			$this->cleanupStaleTemps();
			self::$tempsCleaned = true;
		}
		parent::wired();
	}

	/**
	 * @param array $plan original plan (for template field lists / site title)
	 * @param array $manifest manifest from OliviaBuilder; 'templates' = created
	 * @return array list of file paths written
	 */
	public function generate(array $plan, array &$manifest): array {
		$created = $manifest['templates'] ?? [];
		$targets = array_values(array_unique(array_merge($created, $this->planTemplateNames($plan))));
		if(!$targets) return [];

		$tplModules = $this->planTemplateModules($plan);
		$themeMgr = $this->wire(new OliviaTheme());
		$theme = $themeMgr->resolve($plan);
		$themeMgr->save($theme); // persist so Change-mode rebuilds keep the look
		$dir = $this->wire->config->paths->templates;
		$written = [];

		foreach($targets as $tplName) {
			$tpl = $this->wire->templates->get($tplName);
			if(!$tpl) continue;

			// render standalone (skip profile _main.php / _init.php append)
			if(in_array($tplName, $created, true)) {
				try {
					$tpl->noAppendTemplateFile = 1;
					$tpl->noPrependTemplateFile = 1;
					$this->wire->templates->save($tpl);
				} catch(\Throwable $e) {
					$manifest['errors'][] = "view flags {$tplName}: " . $e->getMessage();
				}
			}

			$moduleBlock = isset($tplModules[$tplName]) ? $this->moduleBlock($tplModules[$tplName], $manifest, $tplName) : '';
			$file = $dir . $tplName . '.php';

			if(is_file($file)) {
				// A template wired to a module must carry its render block; rewrite it
				// (recording the original for rollback). Plain Olivia views just upgrade.
				if($moduleBlock !== '') {
					try {
						$existing = (string) @file_get_contents($file);
						if(strpos($existing, 'Generated by Olivia. Safe to edit or delete.') !== false) {
							if(!$this->backupUpdatedFile($manifest, $file, $existing)) continue;
							$this->writePhpFile($file, $this->viewSource($moduleBlock, $theme));
						}
					} catch(\Throwable $e) {
						$manifest['errors'][] = "view wire {$tplName}: " . $e->getMessage();
					}
				} else {
					$this->upgradeOliviaView($file, $manifest, $theme);
				}
				continue;
			}

			try {
				$this->writePhpFile($file, $this->viewSource($moduleBlock, $theme));
				$written[] = $file;
			} catch(\Throwable $e) {
				$manifest['errors'][] = "view file {$tplName}: " . $e->getMessage();
			}
		}

		$manifest['files'] = array_merge($manifest['files'] ?? [], $written);
		return $written;
	}

	/** Map sanitized template name => module ClassName, from the plan's templates. */
	protected function planTemplateModules(array $plan): array {
		$out = [];
		foreach(($plan['templates'] ?? []) as $t) {
			if(!is_array($t)) continue;
			$name = $this->wire->sanitizer->name((string)($t['name'] ?? ''));
			$mod  = $this->wire->sanitizer->name((string)($t['module'] ?? ''));
			if($name !== '' && $mod !== '') $out[$name] = $mod;
		}
		return $out;
	}

	/**
	 * PHP for the view that outputs a module on this page. Best-effort: only emits
	 * when the module is installed; the render method comes from its recorded skill
	 * (falling back to render()), and a method_exists guard keeps the view safe if
	 * the guess is wrong. Returns '' when there's nothing safe to wire.
	 */
	protected function moduleBlock(string $class, array &$manifest, string $tplName): string {
		try {
			if(!$this->wire->modules->isInstalled($class)) return '';
			$method = $this->wire(new OliviaSkills())->renderMethod($class) ?: 'render';
		} catch(\Throwable $e) {
			$manifest['errors'][] = "view module {$class}: integration skipped (" . mb_substr($e->getMessage(), 0, 200) . ')';
			return '';
		}
		$manifest['template_modules'][$tplName] = ['module' => $class, 'method' => $method];
		$c = var_export($class, true);
		$m = var_export($method, true);
		return "<?php\n"
			. "\t\t// Olivia: $class integration\n"
			. "\t\t\$oliviaMethod = $m;\n"
			. "\t\tif(\$modules->isInstalled($c)):\n"
			. "\t\t\ttry { \$oliviaMod = \$modules->get($c); } catch (\\Throwable \$e) { \$oliviaMod = null; }\n"
			. "\t\t\tif(\$oliviaMod && method_exists(\$oliviaMod, \$oliviaMethod)):\n"
			. "\t\t\t\techo '<div class=\"mt-12\">';\n"
			. "\t\t\t\ttry { echo \$oliviaMod->\$oliviaMethod(\$page); } catch (\\Throwable \$e) {}\n"
			. "\t\t\t\techo '</div>';\n"
			. "\t\t\tendif;\n"
			. "\t\tendif;\n"
			. "\t\t?>";
	}

	protected function planTemplateNames(array $plan): array {
		$out = [];
		foreach(($plan['templates'] ?? []) as $t) {
			$name = $this->wire->sanitizer->name((string)($t['name'] ?? ''));
			if($name !== '') $out[] = $name;
		}
		if($this->planUsesSection($plan['pages'] ?? [])) $out[] = 'section';
		return $out;
	}

	protected function planUsesSection(array $pages): bool {
		foreach($pages as $p) {
			if(!is_array($p)) continue;
			$name = $this->wire->sanitizer->name((string)($p['template'] ?? 'basic-page'));
			if($name === 'section' || $name === 'basic-page' || $name === '') return true;
			if(!empty($p['children']) && is_array($p['children']) && $this->planUsesSection($p['children'])) return true;
		}
		return false;
	}

	protected function upgradeOliviaView(string $file, array &$manifest, array $theme = []): void {
		$existing = (string) @file_get_contents($file);
		$isOliviaView = strpos($existing, 'Generated by Olivia. Safe to edit or delete.') !== false;
		$sig = $theme ? $this->themeSig($theme) : null;
		$needsUpgrade = strpos($existing, 'Olivia view version: ' . self::VIEW_VERSION) === false
			|| ($sig !== null && strpos($existing, 'Olivia theme: ' . $sig) === false);
		if(!$isOliviaView || !$needsUpgrade) return;

		try {
			if(!$this->backupUpdatedFile($manifest, $file, $existing)) return;
			$this->writePhpFile($file, $this->viewSource('', $theme));
		} catch(\Throwable $e) {
			$manifest['errors'][] = "view update " . basename($file) . ": " . $e->getMessage();
		}
	}

	/** Back up an Olivia-owned file only when the resulting Undo manifest stays bounded. */
	protected function backupUpdatedFile(array &$manifest, string $file, string $contents): bool {
		if(isset($manifest['updated_files'][$file])) return true;
		$bytes = strlen($contents);
		if($bytes > self::MAX_BACKUP_FILE_BYTES) {
			$manifest['errors'][] = 'view update skipped: ' . basename($file) . ' exceeds the 512 KB rollback backup limit';
			return false;
		}
		$total = 0;
		foreach(($manifest['updated_files'] ?? []) as $body) if(is_string($body)) $total += strlen($body);
		if($total + $bytes > self::MAX_BACKUP_TOTAL_BYTES) {
			$manifest['errors'][] = 'view update skipped: rollback backups exceed the 4 MB build limit';
			return false;
		}
		$manifest['updated_files'][$file] = $contents;
		return true;
	}

	protected function writePhpFile(string $file, string $source): void {
		$tmp = $file . '.' . getmypid() . '.' . str_replace('.', '', uniqid('', true)) . '.tmp';
		try {
			$this->wire->files->filePutContents($tmp, $source);
			if(!@rename($tmp, $file)) {
				throw new \RuntimeException('Could not replace Olivia view PHP');
			}
		} finally {
			if(is_file($tmp)) @unlink($tmp);
		}
	}

	public function cleanupStaleTemps(): void {
		$files = glob($this->wire->config->paths->templates . '*.php.*.tmp');
		if(!is_array($files)) return;
		$cutoff = time() - self::TMP_TTL;
		foreach($files as $file) {
			$name = basename((string) $file);
			if(!$this->isTempName($name)) continue;
			$mtime = @filemtime($file);
			if($mtime !== false && $mtime < $cutoff) @unlink($file);
		}
	}

	protected function isTempName(string $name): bool {
		return (bool) preg_match('/^[A-Za-z0-9_-]+\.php\.\d+\.[a-f0-9]+\.tmp$/', $name);
	}

	/**
	 * Give the site a styled home landing page without touching the profile's
	 * home.php: point the 'home' template at an alternate view file via
	 * altFilename, and (optionally) set the home page title to the site title.
	 * All changes recorded in the manifest for rollback.
	 *
	 * @param array $plan
	 * @param array $manifest
	 * @return bool
	 */
	public function generateHome(array $plan, array &$manifest): bool {
		$home = $this->wire->templates->get('home');
		if(!$home) return false;

		// only worth a landing page if the site has real (non-system) sections
		$root = $this->wire->pages->get('/');
		$sections = $this->sectionPages($root);
		if(!$sections->count()) return false;

		// point home template at our alt view AND stop the profile _main.php from
		// being appended (our view is a full standalone document). Record old values.
		$changed = false;
		if((string) $home->altFilename !== 'olivia_home') {
			$manifest['home_alt'] = (string) $home->altFilename;
			$home->altFilename = 'olivia_home';
			$changed = true;
		}
		if(!$home->noAppendTemplateFile || !$home->noPrependTemplateFile) {
			$manifest['home_noappend'] = [(int) $home->noAppendTemplateFile, (int) $home->noPrependTemplateFile];
			$home->noAppendTemplateFile = 1;
			$home->noPrependTemplateFile = 1;
			$changed = true;
		}
		if($changed) $this->wire->templates->save($home);

		// set home page title to the site title (record old)
		$siteTitle = trim((string)($plan['site']['title'] ?? ''));
		if($siteTitle !== '' && $root->title !== $siteTitle) {
			$manifest['home_title'] = $root->title;
			$root->of(false);
			$root->title = $siteTitle;
			$root->save();
		}

		$file = $this->wire->config->paths->templates . 'olivia_home.php';
		$theme = $this->wire(new OliviaTheme())->resolve($plan);
		$homeSource = $this->homeSource((string)($plan['site']['tagline'] ?? ''), $theme);
		if(!is_file($file)) {
			try {
				$this->writePhpFile($file, $homeSource);
				$manifest['files'][] = $file;
			} catch(\Throwable $e) {
				$manifest['errors'][] = 'home view: ' . $e->getMessage();
			}
		} else {
			$existing = (string) @file_get_contents($file);
			$isOliviaHome = strpos($existing, 'Generated by Olivia. Home landing') !== false;
			$needsUpgrade = strpos($existing, 'Olivia home version: ' . self::HOME_VERSION) === false
				|| strpos($existing, 'Olivia theme: ' . $this->themeSig($theme)) === false;
			if($isOliviaHome && $needsUpgrade) {
				try {
					if(!$this->backupUpdatedFile($manifest, $file, $existing)) return true;
					$this->writePhpFile($file, $homeSource);
				} catch(\Throwable $e) {
					$manifest['errors'][] = 'home view update: ' . $e->getMessage();
				}
			}
		}
		return true;
	}

	/** Top-level pages that are real sections (exclude admin/trash/404). */
	protected function sectionPages(Page $root): PageArray {
		$skip = $this->wire->config->trashPageID . '|' . $this->wire->config->http404PageID;
		return $root->children("include=hidden, template!=admin, id!=$skip");
	}

